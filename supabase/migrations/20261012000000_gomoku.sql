-- 五子棋对战（自由规则，15×15，黑先，连成 5 子或更多获胜）。
-- 数据库是唯一权威：轮到谁、能不能落在这里、谁赢了，都由触发器决定，前端改不了。
-- 在 Supabase SQL Editor 里整段运行（可重复运行）。需要先运行过前面的迁移（is_member / my_person）。

create table if not exists public.gomoku_games (
  id bigint generated by default as identity primary key,
  black text not null check (black in ('Carol', 'Allen')),
  white text not null check (white in ('Carol', 'Allen')),
  status text not null default 'playing' check (status in ('playing', 'finished')),
  winner text check (winner in ('Carol', 'Allen')),   -- 结束时为空 = 平局（下满棋盘）
  move_count int not null default 0,
  created_by uuid references auth.users (id) on delete set null default auth.uid(),
  created_at timestamptz not null default now(),
  finished_at timestamptz,
  check (black <> white)
);
-- 同一时间只有一局在下
create unique index if not exists gomoku_one_active_game on public.gomoku_games ((true)) where status = 'playing';

create table if not exists public.gomoku_moves (
  game_id bigint not null references public.gomoku_games (id) on delete cascade,
  move_no int not null,
  person text not null check (person in ('Carol', 'Allen')),
  x int not null check (x between 0 and 14),
  y int not null check (y between 0 and 14),
  created_at timestamptz not null default now(),
  primary key (game_id, move_no),
  unique (game_id, x, y)
);

-- ---------- 开局：先手每局轮换，第一局由开局的人执黑 ----------
create or replace function public.gomoku_games_before_insert()
returns trigger
language plpgsql security definer set search_path = ''
as $$
declare
  v_me text := public.my_person();
  v_last_black text;
begin
  -- No admin bypass here: inside a security definer function current_user is the owner, so a
  -- "current_user not in (authenticated, anon)" check would skip every rule for everyone.
  if not public.is_member() then raise exception '这个账号没有使用权限'; end if;
  if exists (select 1 from public.gomoku_games where status = 'playing') then
    raise exception '还有一局没下完，先下完或认输';
  end if;
  select black into v_last_black from public.gomoku_games order by id desc limit 1;
  new.black := case when v_last_black is null then v_me when v_last_black = 'Carol' then 'Allen' else 'Carol' end;
  new.white := case when new.black = 'Carol' then 'Allen' else 'Carol' end;
  new.status := 'playing';
  new.winner := null;
  new.move_count := 0;
  new.created_by := auth.uid();
  new.created_at := now();
  new.finished_at := null;
  return new;
end $$;

drop trigger if exists gomoku_games_before_insert on public.gomoku_games;
create trigger gomoku_games_before_insert
before insert on public.gomoku_games
for each row execute function public.gomoku_games_before_insert();

-- ---------- 落子前：轮到谁、局是否还在下、格子是否空着 ----------
create or replace function public.gomoku_moves_before_insert()
returns trigger
language plpgsql security definer set search_path = ''
as $$
declare
  v_game public.gomoku_games;
  v_me text := public.my_person();
begin
  if not public.is_member() then raise exception '这个账号没有使用权限'; end if;
  -- 锁住这一局，两台手机同时落子时按先后排队
  select * into v_game from public.gomoku_games where id = new.game_id for update;
  if v_game.id is null then raise exception '棋局不存在'; end if;
  if v_game.status <> 'playing' then raise exception '这一局已经结束了'; end if;
  if v_me is distinct from (case when v_game.move_count % 2 = 0 then v_game.black else v_game.white end) then
    raise exception '还没轮到你';
  end if;
  if new.x is null or new.y is null or new.x not between 0 and 14 or new.y not between 0 and 14 then
    raise exception '不能下在棋盘外';
  end if;
  if exists (select 1 from public.gomoku_moves where game_id = new.game_id and x = new.x and y = new.y) then
    raise exception '这里已经有子了';
  end if;
  new.person := v_me;
  new.move_no := v_game.move_count + 1;
  new.created_at := now();
  return new;
end $$;

drop trigger if exists gomoku_moves_before_insert on public.gomoku_moves;
create trigger gomoku_moves_before_insert
before insert on public.gomoku_moves
for each row execute function public.gomoku_moves_before_insert();

-- ---------- 落子后：判断连五，更新棋局 ----------
create or replace function public.gomoku_moves_after_insert()
returns trigger
language plpgsql security definer set search_path = ''
as $$
declare
  v_dirs int[][] := array[[1, 0], [0, 1], [1, 1], [1, -1]];
  v_count int;
  v_step int;
  v_sign int;
  v_won boolean := false;
begin
  for d in 1..4 loop
    v_count := 1;
    foreach v_sign in array array[1, -1] loop
      v_step := 1;
      while exists (
        select 1 from public.gomoku_moves
        where game_id = new.game_id and person = new.person
          and x = new.x + v_dirs[d][1] * v_step * v_sign
          and y = new.y + v_dirs[d][2] * v_step * v_sign
      ) loop
        v_count := v_count + 1;
        v_step := v_step + 1;
      end loop;
    end loop;
    if v_count >= 5 then v_won := true; exit; end if;
  end loop;

  update public.gomoku_games
  set move_count = new.move_no,
      status = case when v_won or new.move_no >= 225 then 'finished' else 'playing' end,
      winner = case when v_won then new.person else null end,
      finished_at = case when v_won or new.move_no >= 225 then now() else null end
  where id = new.game_id;
  return null;
end $$;

drop trigger if exists gomoku_moves_after_insert on public.gomoku_moves;
create trigger gomoku_moves_after_insert
after insert on public.gomoku_moves
for each row execute function public.gomoku_moves_after_insert();

-- ---------- 认输：只能认输自己参与、还在下的那一局 ----------
create or replace function public.gomoku_resign(p_game bigint)
returns void
language plpgsql security definer set search_path = ''
as $$
declare
  v_me text := public.my_person();
begin
  if not public.is_member() then raise exception '这个账号没有使用权限'; end if;
  update public.gomoku_games
  set status = 'finished', winner = case when v_me = black then white else black end, finished_at = now()
  where id = p_game and status = 'playing' and v_me in (black, white);
  if not found then raise exception '没有可以认输的棋局'; end if;
end $$;

revoke execute on function public.gomoku_games_before_insert(), public.gomoku_moves_before_insert(), public.gomoku_moves_after_insert() from public, anon;
revoke execute on function public.gomoku_resign(bigint) from public, anon;
grant execute on function public.gomoku_resign(bigint) to authenticated;

-- ---------- 权限：两人可读；只能新开局和落子，不能修改或删除 ----------
alter table public.gomoku_games enable row level security;
alter table public.gomoku_moves enable row level security;
revoke all on public.gomoku_games, public.gomoku_moves from anon, authenticated;
grant select, insert on public.gomoku_games, public.gomoku_moves to authenticated;

drop policy if exists "members read games" on public.gomoku_games;
create policy "members read games" on public.gomoku_games for select to authenticated using (public.is_member());
drop policy if exists "members start games" on public.gomoku_games;
create policy "members start games" on public.gomoku_games for insert to authenticated with check (public.is_member());

drop policy if exists "members read moves" on public.gomoku_moves;
create policy "members read moves" on public.gomoku_moves for select to authenticated using (public.is_member());
drop policy if exists "members play moves" on public.gomoku_moves;
create policy "members play moves" on public.gomoku_moves for insert to authenticated with check (public.is_member() and person = public.my_person());

